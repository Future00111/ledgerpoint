import test from 'node:test';
import assert from 'node:assert/strict';
import {readFileSync} from 'node:fs';
import {calculateSyntheticPlan1,syntheticNoticeDigest,plan1SyntheticContract as contract} from './plan1SyntheticContract.mjs';
import {loadPinnedEvidence} from '../../../../../../tools/payroll-specification/studentLoans.mjs';
const pack=JSON.parse(readFileSync(new URL('./fixtures/plan1-notice-start-stop-2026-27.json',import.meta.url)));
const corpus=loadPinnedEvidence();
const active=pack.cases.find(c=>c.id==='first-start-payday-upper-boundary');
function envelopeFor(input){
  return {contractVersion:contract.version,ruleVersion:contract.ruleVersion,purpose:contract.purpose,
    input:structuredClone(input),verifiedNotices:input.notices.map(n=>({noticeId:n.id,noticeDigest:syntheticNoticeDigest(n),
      identityVerified:true,firstPracticalPayday:n.firstAvailablePayday,availabilityVerified:true}))};
}
for (const scenario of pack.cases) test(`combined synthetic contract: ${scenario.id}`,()=>{
  const envelope=envelopeFor(scenario.input),before=JSON.stringify(envelope);
  const result=calculateSyntheticPlan1(envelope);
  assert.equal(result.deductionMinor,scenario.expected.deductionMinor);
  assert.equal(result.instructionActive,scenario.expected.instructionActive);
  assert.equal(result.reason,scenario.expected.reason);
  assert.equal(result.contractVersion,contract.version);assert.equal(result.ruleVersion,contract.ruleVersion);
  assert.equal(result.qualified,false);assert.equal(result.notForPayroll,true);
  assert.equal(result.status,'unqualified_synthetic_reference_contract');
  assert.match(result.inputDigest,/^[a-f0-9]{64}$/);
  assert.equal(JSON.stringify(envelope),before);
  if (result.instructionActive) {
    const reference=corpus.cases.find(c=>c.id===scenario.provenance.amountSource);
    assert.equal(reference.expected.deductionMinor,result.deductionMinor);
    assert.equal(result.calculation.specificationId,contract.ruleVersion);
  } else assert.equal(result.calculation,null);
});
test('zero and threshold expectations are explicit engineering applications; official one-penny boundary is preserved',()=>{
  // First four expected zeros follow the pinned threshold/whole-pound rule. The final
  // pair is independently supplied by HMRC Plan_1 rows11/12, never generated by this code.
  for(const [payMinor,expected] of [['0','0'],['51729','0'],['51730','0'],['51731','0'],['52841','0'],['52842','100']]){
    const result=calculateSyntheticPlan1(envelopeFor({...active.input,payMinor}));
    assert.equal(result.deductionMinor,expected);assert.equal(result.calculation.thresholdMinor,'51730');
    assert.equal(result.calculation.ratePercent,'9');
  }
});
test('exact version, explicit purpose, complete verified assertions and content binding are mandatory',()=>{
  for(const mutate of [
    e=>delete e.ruleVersion,e=>e.ruleVersion='student-loans-2025-26-review-v1',
    e=>e.contractVersion='v2',e=>e.purpose='production',e=>delete e.purpose,
    e=>e.unexpected=true,e=>e.verifiedNotices=[],e=>delete e.verifiedNotices,
    e=>e.verifiedNotices[0].identityVerified=false,e=>e.verifiedNotices[0].identityVerified='true',
    e=>e.verifiedNotices[0].availabilityVerified=false,
    e=>delete e.verifiedNotices[0].availabilityVerified,
    e=>e.verifiedNotices[0].firstPracticalPayday='2026-04-24',
    e=>e.verifiedNotices[0].noticeId='another-notice',e=>e.verifiedNotices[0].noticeDigest='0'.repeat(64),
    e=>e.input.notices[0].availabilityEvidence='changed after assertion',
    e=>e.input.notices[0].effectiveDate='2026-04-09',
    e=>e.input.notices[0].receivedDate='2026-04-07',
    e=>e.verifiedNotices[0].unrecognised=true,
  ]) {const envelope=envelopeFor(active.input);mutate(envelope);assert.throws(()=>calculateSyntheticPlan1(envelope),/^Error: SYNTHETIC_/);}
});
test('conflicting or unsupported instructions and unavailable cutoff evidence remain rejected even when assertions are true',()=>{
  for(const mutate of [
    i=>i.notices.push({...i.notices[0],id:'conflicting-start'}),
    i=>i.notices[0].type='P45',i=>i.otherInstructions=['starter'],i=>i.otherInstructions=['GNS'],
    i=>i.notices[0].plan='plan_2',i=>i.notices[0].employmentId='other-employee',
    i=>i.notices[0].firstAvailablePayday=i.notices[0].effectiveDate,
    i=>i.notices[0].receivedDate='2026-04-18',i=>i.notices[0].availabilityEvidence='',
    i=>i.taxYear='2027-28',i=>i.plan='plan_2',i=>i.frequency='monthly',
    i=>i.offPayroll=true,i=>i.protectedEarnings=true,i=>i.concurrentLoan=true,
    i=>i.payMinor='-1',i=>i.payMinor='1.00',i=>i.payMinor='01',i=>i.payMinor=52842,
    i=>i.paymentDate='2027-04-06',i=>i.paymentDate='2026-02-30',
  ]) {const input=structuredClone(active.input);mutate(input);assert.throws(()=>calculateSyntheticPlan1(envelopeFor(input)),/^Error: (NOTICE_|SYNTHETIC_NOTICE_FIELDS)/);}
});
test('stopped cases cannot bypass input validation and duplicated verification cannot cover a second notice',()=>{
  const stopped=pack.cases.find(c=>c.id==='first-stop-payday');
  const invalid=envelopeFor({...stopped.input,payMinor:'-1'});
  assert.throws(()=>calculateSyntheticPlan1(invalid),/NOTICE_INPUT_FIELDS/);
  const duplicate=envelopeFor(stopped.input);duplicate.verifiedNotices[1]=structuredClone(duplicate.verifiedNotices[0]);
  assert.throws(()=>calculateSyntheticPlan1(duplicate),/SYNTHETIC_NOTICE_VERIFICATION/);
});
test('repeatable outputs have stable canonical digests and no shared mutable trace',()=>{
  const envelope=envelopeFor(active.input),first=calculateSyntheticPlan1(envelope);
  const reordered=Object.fromEntries(Object.entries(envelope).reverse());
  assert.deepEqual(calculateSyntheticPlan1(reordered),first);
  const differentPay=envelopeFor({...active.input,payMinor:'52841'});
  assert.notEqual(calculateSyntheticPlan1(differentPay).inputDigest,first.inputDigest);
  first.calculation.deductionMinor='999';
  assert.equal(calculateSyntheticPlan1(envelope).calculation.deductionMinor,'100');
  const notice=active.input.notices[0];
  assert.equal(syntheticNoticeDigest(Object.fromEntries(Object.entries(notice).reverse())),syntheticNoticeDigest(notice));
});
test('machine-readable input/output contract remains linked to the original unqualified case',()=>{
  const registry=JSON.parse(readFileSync(new URL('../../../../../../docs/development/tax-payroll-supported-cases.json',import.meta.url)));
  const row=registry.cases.find(c=>c.id==='payroll-loan-plan_1-2026-27');
  const declared=row.fixturePrerequisite.syntheticInputContract;
  assert.equal(row.status,'unsupported');assert.equal(row.qualificationEvidence,null);
  assert.equal(declared.qualificationEvidence,null);
  assert.equal(declared.contractVersion,contract.version);assert.equal(declared.ruleVersion,contract.ruleVersion);
  assert.deepEqual(Object.keys(envelopeFor(active.input)),declared.requiredEnvelopeFields);
  assert.deepEqual(Object.keys(envelopeFor(active.input).verifiedNotices[0]),declared.requiredNoticeAssertions);
  assert.deepEqual(Object.keys(calculateSyntheticPlan1(envelopeFor(active.input))),declared.resultFields);
});
